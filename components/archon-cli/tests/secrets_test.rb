require_relative 'test_helpers'

def store_path(fixture)
  File.join(fixture[:home], '.local/share/archon/secrets/secrets.env')
end

def write_store(fixture, content, mode: 0o600)
  path = store_path(fixture)
  FileUtils.mkdir_p(File.dirname(path))
  File.write(path, content)
  File.chmod(mode, path)
  path
end

def secrets_repository(fixture, name, template: nil, ignore: true)
  repository = initialize_repository(File.join(fixture[:home], 'projects/personal/owner', name))
  File.write(File.join(repository[:path], '.gitignore'), ".env\n") if ignore
  File.write(File.join(repository[:path], '.env.template'), template) if template
  repository[:path]
end

def mode(path)
  File.stat(path).mode & 0o777
end

HEADER = "# Generated by `archon projects secrets sync`. Edit .env.template instead.\n"

test('secrets init creates a private store with every name') do
  fixture do |fixture|
    result = run_archon(%w[projects secrets init])
    equal 0, result[:status]
    path = store_path(fixture)
    assert result[:stdout].include?("Created #{path}")
    equal "GITHUB_TOKEN=\n", File.read(path)
    equal 0o600, mode(path)
    equal 0o700, mode(File.dirname(path))
  end
end

test('secrets init appends only missing names and preserves existing values') do
  fixture do |fixture|
    path = write_store(fixture, "# mine\nOTHER=keep")
    result = run_archon(%w[projects secrets init])
    equal 0, result[:status]
    assert result[:stdout].include?("Added GITHUB_TOKEN to #{path}")
    equal "# mine\nOTHER=keep\nGITHUB_TOKEN=\n", File.read(path)
  end
end

test('secrets init leaves a complete store untouched') do
  fixture do |fixture|
    path = write_store(fixture, "GITHUB_TOKEN=secret\n")
    File.utime(Time.at(0), Time.at(0), path)
    result = run_archon(%w[projects secrets init])
    equal 0, result[:status]
    assert result[:stdout].include?('Nothing to do')
    equal "GITHUB_TOKEN=secret\n", File.read(path)
    equal Time.at(0), File.mtime(path)
  end
end

test('secrets sync requires an existing private store') do
  fixture do |fixture|
    repository = secrets_repository(fixture, 'app', template: "TOKEN=${GITHUB_TOKEN}\n")
    result = run_archon(%w[projects secrets sync])
    equal 1, result[:status]
    assert result[:stderr].include?('archon projects secrets init')
    write_store(fixture, "GITHUB_TOKEN=secret\n", mode: 0o640)
    result = run_archon(%w[projects secrets sync])
    equal 1, result[:status]
    assert result[:stderr].include?('chmod 600')
    assert !File.exist?(File.join(repository, '.env'))
  end
end

test('secrets sync renders placeholders only and reports created, unchanged, and updated') do
  fixture do |fixture|
    write_store(fixture, "GITHUB_TOKEN=a$b=${GITHUB_TOKEN}\n")
    repository = secrets_repository(fixture, 'app', template: "TOKEN=${GITHUB_TOKEN}\nPRICE=$5\nRAW=$OTHER\n")
    env = File.join(repository, '.env')
    result = run_archon(%w[projects secrets sync])
    equal 0, result[:status]
    equal "created    owner/app/.env\n", result[:stdout]
    equal "#{HEADER}TOKEN=a$b=${GITHUB_TOKEN}\nPRICE=$5\nRAW=$OTHER\n", File.read(env)
    equal 0o600, mode(env)

    File.utime(Time.at(0), Time.at(0), env)
    result = run_archon(%w[projects secrets sync])
    equal "unchanged  owner/app/.env\n", result[:stdout]
    equal Time.at(0), File.mtime(env)

    write_store(fixture, "GITHUB_TOKEN=rotated\n")
    result = run_archon(%w[projects secrets sync])
    equal 0, result[:status]
    equal "updated    owner/app/.env\n", result[:stdout]
    equal "#{HEADER}TOKEN=rotated\nPRICE=$5\nRAW=$OTHER\n", File.read(env)

    File.write(File.join(repository, '.env.template'), "TOKEN=${GITHUB_TOKEN}\n")
    equal "updated    owner/app/.env\n", run_archon(%w[projects secrets sync])[:stdout]
    equal "#{HEADER}TOKEN=rotated\n", File.read(env)
    equal [], Dir.children(repository).grep(/\.tmp\z/)
  end
end

test('secrets sync skips unrenderable repositories and still processes the rest') do
  fixture do |fixture|
    write_store(fixture, "GITHUB_TOKEN=secret\n")
    unknown = secrets_repository(fixture, 'a-unknown', template: "X=${NOT_ALLOWED}\n")
    good = secrets_repository(fixture, 'b-good', template: "X=${GITHUB_TOKEN}\n")
    unignored = secrets_repository(fixture, 'c-unignored', template: "X=${GITHUB_TOKEN}\n", ignore: false)
    tracked = secrets_repository(fixture, 'd-tracked', template: "X=${GITHUB_TOKEN}\n", ignore: false)
    File.write(File.join(tracked, '.env'), "tracked\n")
    git(tracked, 'add', '.env')
    git(tracked, 'commit', '-qm', 'track env')
    File.write(File.join(tracked, '.gitignore'), ".env\n")
    result = run_archon(%w[projects secrets sync])
    equal 1, result[:status]
    equal <<~TEXT, result[:stdout]
      skipped    owner/a-unknown/.env  (unknown name: NOT_ALLOWED)
      created    owner/b-good/.env
      skipped    owner/c-unignored/.env  (.env is not ignored by Git)
      skipped    owner/d-tracked/.env  (.env is not ignored by Git)
    TEXT
    assert !File.exist?(File.join(unknown, '.env'))
    assert File.exist?(File.join(good, '.env'))
    assert !File.exist?(File.join(unignored, '.env'))
    equal "tracked\n", File.read(File.join(tracked, '.env'))
  end
end

test('secrets sync skips templates that use empty values and warns about unknown store names') do
  fixture do |fixture|
    write_store(fixture, "GITHUB_TOKEN=\nEXTRA=value\n")
    repository = secrets_repository(fixture, 'app', template: "X=${GITHUB_TOKEN}\n")
    File.write(File.join(repository, '.env'), "old\n")
    result = run_archon(%w[projects secrets sync])
    equal 1, result[:status]
    equal "skipped    owner/app/.env  (empty value: GITHUB_TOKEN)\n", result[:stdout]
    assert result[:stderr].include?('Ignoring unknown secret name')
    assert result[:stderr].include?('EXTRA')
    equal "old\n", File.read(File.join(repository, '.env'))
  end
end

test('an unknown store name alone does not fail secrets sync') do
  fixture do |fixture|
    write_store(fixture, "GITHUB_TOKEN=secret\nEXTRA=value\n")
    secrets_repository(fixture, 'app', template: "X=${GITHUB_TOKEN}\n")
    result = run_archon(%w[projects secrets sync])
    equal 0, result[:status]
    assert result[:stderr].include?('EXTRA')
  end
end

test('secrets sync ignores repositories without templates') do
  fixture do |fixture|
    write_store(fixture, "GITHUB_TOKEN=secret\n")
    secrets_repository(fixture, 'plain')
    result = run_archon(%w[projects secrets sync])
    equal 0, result[:status]
    assert result[:stdout].start_with?('No .env.template files found')
    secrets_repository(fixture, 'app', template: "X=${GITHUB_TOKEN}\n")
    equal "created    owner/app/.env\n", run_archon(%w[projects secrets sync])[:stdout]
  end
end

test('secrets help and usage errors') do
  fixture do
    result = run_archon(%w[projects secrets])
    equal 2, result[:status]
    assert result[:stderr].include?('Missing secrets command.')
    result = run_archon(%w[projects secrets help])
    equal 0, result[:status]
    assert result[:stdout].include?('Usage: archon projects secrets <command>')
    assert run_archon(%w[projects secrets help sync])[:stdout].include?('Usage: archon projects secrets sync')
    assert run_archon(%w[projects secrets init --help])[:stdout].include?('Usage: archon projects secrets init')
    assert run_archon(%w[projects help secrets])[:stdout].include?('Usage: archon projects secrets <command>')
    assert run_archon(%w[projects help])[:stdout].include?('secrets  Generate .env files')
    equal 2, run_archon(%w[projects secrets bogus])[:status]
    result = run_archon(%w[projects secrets sync --dry-run])
    equal 2, result[:status]
    assert result[:stderr].include?('Unexpected sync option: --dry-run')
  end
end

test('the secrets store follows XDG_DATA_HOME') do
  fixture do |fixture|
    data_home = File.join(fixture[:root], 'data')
    equal 0, run_archon(%w[projects secrets init], 'XDG_DATA_HOME' => data_home)[:status]
    assert File.exist?(File.join(data_home, 'archon/secrets/secrets.env'))
    assert !File.exist?(store_path(fixture))
    equal 0, run_archon(%w[projects secrets init], 'XDG_DATA_HOME' => '')[:status]
    assert File.exist?(store_path(fixture))
  end
end
